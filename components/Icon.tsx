/** Ionicons names that were solid shapes: drawn filled, so a liked heart or saved bookmark still reads as "on". */
const FILLED = new Set(["heart", "star", "bookmark", "water", "flame", "moon"]);

export type IconSet = "ion" | "feather" | "mci";

export type IconProps = {
  name: string;
  /** Which set `name` comes from; only used when Lucide has no match. */
  set?: IconSet;
  size?: number;
  color?: string;
  style?: StyleProp<ViewStyle | TextStyle>;
  strokeWidth?: number;
  accessibilityLabel?: string;
  accessible?: boolean;
  testID?: string;
};

export function hasLucideIcon(name: string) {
  return name in LUCIDE;
}

export function Icon({ name, set = "ion", size = 24, color, style, strokeWidth, ...rest }: IconProps) {
  const Lucide = LUCIDE[name];
  if (Lucide) {
    const filled = set === "ion" && FILLED.has(name);
    return (
      <Lucide
        size={size}
        color={color}
        // Thin strokes vanish at small sizes; keep about 1.6px of ink.
        strokeWidth={strokeWidth ?? (size <= 16 ? 2.25 : 2)}
        fill={filled ? color : "none"}
        style={style as StyleProp<ViewStyle>}
        {...rest}
      />
    );
  }
  const props = { size, color, style: style as StyleProp<TextStyle>, ...rest };
  if (set === "feather") return <Feather name={name as React.ComponentProps<typeof Feather>["name"]} {...props} />;
  if (set === "mci") return <MaterialCommunityIcons name={name as React.ComponentProps<typeof MaterialCommunityIcons>["name"]} {...props} />;
  return <Ionicons name={name as React.ComponentProps<typeof Ionicons>["name"]} {...props} />;
}
